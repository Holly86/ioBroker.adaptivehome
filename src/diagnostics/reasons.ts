const executionReasons = new Set([
	'unknown_function',
	'device_busy',
	'device_uncertain_reconcile',
	'revision_or_scope_changed',
	'intent_expired_or_disabled',
	'maintenance',
	'binding_not_authorized',
	'value_type',
	'hard_limit',
	'unsupported_value',
	'state_type_or_missing',
	'state_readonly',
	'state_unreadable',
	'source_unit_mismatch',
	'audit_retry_wait',
	'dependency_unconfirmed',
	'protection_unknown',
	'conflicting_protection',
	'technical_protection',
	'minimum_service',
	'outside_operating_window',
	'manual_priority',
	'command_budget',
	'minimum_dwell',
	'preflight_stale',
	'awaiting_feedback',
	'dispatch_conditions_changed',
	'deadline_exceeded',
	'backend_scope',
	'protected_state',
	'unknown_integration',
	'unsupported_capability',
	'unit_mismatch',
]);
export function executionReason(error: unknown): string {
	return error instanceof Error && executionReasons.has(error.message) ? error.message : 'execution_failed';
}
